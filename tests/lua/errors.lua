-- Errors: their messages and places, pcall, xpcall, error, assert
local function try(f, ...) local ok, e = pcall(f, ...) return ok, e end
print(try(function() local t = nil; return t.x end))
print(try(function() return undefinedglobal.field end))
print(try(function() local t = {} ; return t.a.b end))
print(try(function() return 1 + nil end))
print(try(function() local s = "abc"; return s + 1 end))
print(try(function() return {} .. "x" end))
print(try(function() return 1 < "2" end))
print(try(function() return {} < {} end))
print(try(function() nofunction() end))
print(try(function() local t = {} ; t.method() end))
print(try(function() local t = {} ; t:method() end))
print(try(function() return #5 end))
print(try(function() return -{} end))
print(try(function() error("plain") end))
print(try(function() error("no place", 0) end))
print(type(select(2, try(function() error({code = 42}) end))))
print(select(2, pcall(error, {code = 7})).code)
print(try(function() error() end))
print(try(function() assert(false) end))
print(try(function() assert(nil, "custom") end))
print(try(function() assert(1 == 1, "fine") return "passed" end))
print(xpcall(function() error("in xpcall") end, function(m) return "handled: " .. m end))
print(xpcall(function(a, b) return a + b end, print, 2, 3))
print(try(function() local x = 5; x() end))
print(try(function() for i = 1, "x" do end end))
print(try(string.rep))
print(try(string.sub))
print(try(math.floor, "x"))
print(try(setmetatable, 1, {}))
print(try(function() return ("x"):bad() end))
print(try(function() local a = {} ; return a.b.c.d end))
print(pcall(pcall))
print(select("#", pcall(function() return 1, 2, 3 end)))
local ok, msg = pcall(function() local function deep(n) return deep(n + 1) + 1 end return deep(1) end)
print(ok, msg:match("stack overflow") ~= nil)
print(tostring(nil) .. "", tostring(false))
